// Exercise the actual admin read/edit/write bridge without changing live records.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
let written;
const row = {id:'vendor-check',name:'Vendor',status:'Active',category_id:'food',logo_path:'old-logo',description:'old-description',featured:false,trend:8,cover_image_url:'old-cover',gallery_images:[],payload:{profilePicture:'stale-logo',logoPath:'stale-logo',description:'stale-description',shortDescription:'stale-description',isTrending:false,offers:[{id:'existing-offer',titleEn:'Existing offer'}]},couponly_categories:{name:'Food'},couponly_vendor_subcategories:[{subcategory_id:'rice',couponly_subcategories:{name:'Rice'}}]};
const client = {from:()=>({select:()=>({eq:()=>({maybeSingle:async()=>({data:row,error:null})})}),update:value=>({eq:async()=>{written=value;return {error:null};}})})};
const source = path.resolve(__dirname,'../src/firebase/firestore.ts');
const compiled = new Module(source,module);
compiled.require = name => {assert.equal(name,'@/lib/supabase');return {supabase:client};};
compiled._compile(ts.transpileModule(fs.readFileSync(source,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,source);
(async()=>{
  const {doc,getDoc,updateDoc} = compiled.exports;
  const reference=doc(null,'vendors','vendor-check');
  const current=(await getDoc(reference)).data();
  assert.equal(current.profilePicture,'old-logo');
  assert.equal(current.shortDescription,'old-description');
  assert.equal(current.isTrending,true);
  assert.deepEqual(current.subcategory,['Rice']);
  await updateDoc(reference,{profilePicture:'new-logo',shortDescription:'new-description',isTrending:false,coverImage:'new-cover',galleryImages:['gallery-photo']});
  assert.equal(written.logo_path,'new-logo');
  assert.equal(written.description,'new-description');
  assert.equal(written.featured,false);
  assert.equal(written.trend,0);
  assert.equal(written.cover_image_url,'new-cover');
  assert.deepEqual(written.gallery_images,['gallery-photo']);
  assert.equal(written.payload.offers[0].id,'existing-offer');
  row.trend=0;
  row.featured=true;
  assert.equal((await getDoc(reference)).data().isTrending,false);
  await updateDoc(reference,{shortDescription:'',profilePicture:'',isTrending:true});
  assert.equal(written.description,'');
  assert.equal(written.logo_path,'');
  assert.equal(written.featured,true);
  assert.equal(written.trend,1);
  await updateDoc(reference,{isTrending:true,trend:8,newest:7,sortOrder:3});
  assert.equal(written.trend,8);
  assert.equal(written.newest,7);
  assert.equal(written.sort_order,3);
  await assert.rejects(updateDoc(reference,{newest:-1}),/non-negative whole numbers/);
  await assert.rejects(updateDoc(reference,{sortOrder:0.5}),/non-negative whole numbers/);
  console.log('Admin canonical branding, empty-field clearing, taxonomy, and offer preservation: passed');
})().catch(error=>{console.error(error.message);process.exitCode=1;});
